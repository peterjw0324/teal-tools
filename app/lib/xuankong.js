// 玄空挨星定義!BA3:BD11：數 → 國字、宮名
const NUMERALS = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
const PALACE_NAMES = ['', '坎', '坤', '震', '巽', '中', '乾', '兌', '艮', '離'];

// 九宮格位置（玄空盤!AW3:AX50 的第 n 山，坐山為第 1 山）
// 上排 10、13（向）、16；中排 7、中宮、19；下排 4、1（坐）、22
const GRID_POSITIONS = [10, 13, 16, 7, 19, 4, 1, 22];

const TAI_JI = 5; // 玄空盤!Y3 太極點

// Excel MOD：結果與除數同號
const mod = (a, b) => a - b * Math.floor(a / b);

function lookupDeg(deg) {
  let row = DEG_TABLE[0];
  for (const r of DEG_TABLE) {
    if (r[0] <= deg) row = r;
    else break;
  }
  return row;
}

// 玄空盤!AL3：INT(LEFT(VLOOKUP(INT(1+MOD(117+年-1,180)), AH3:AY183, 10), 1))；年 < 0 時用 117+年
export function periodOf(year) {
  const index = year < 0 ? Math.floor(1 + mod(117 + year, 180)) : Math.floor(1 + mod(117 + year - 1, 180));
  return Number(PERIOD_180[index - 1]);
}

// sitDeg = 坐山度數（玄空盤!O25），子在 0°；超出 0–360 的值先換回 0–360
export function chart({ year, sitDeg }) {
  const period = periodOf(year);
  const deg = norm(sitDeg);

  // AD18、AH18、AJ18：坐山、是否兼、下卦／起星
  const [, sitText, kind] = lookupDeg(deg);
  const sit = sitText[0];
  const jian = sitText[1] === '兼';
  // AF18：向 = VLOOKUP(1+MOD(度數+180-1,360)) 的第一個字
  const face = lookupDeg(1 + mod(deg + 180 - 1, 360))[1][0];

  // AT/AW 欄：從坐山起順時針數第 n 山；Y19:AA21 = 該山所屬的卦（宮的洛書數）
  const start = RING.indexOf(sit);
  const palaceAt = (n) => GUA_OF[RING[(start + n - 1) % 24]];
  const sitPalace = palaceAt(1);   // Z21
  const facePalace = palaceAt(13); // Z19
  const yuan = YUAN_OF[sit];       // AD20：坐山的地天人

  // 運星（H9 等）：1+MOD(運+宮-5-1, 9)
  const yun = (p) => 1 + mod(period + p - TAI_JI - 1, 9);

  // 中宮山星 K12、向星 L12：運盤坐宮／向宮的星入中；兼山（起星）時換成替星
  const center = (n) => (jian ? STAR_TABLE[`${n}${yuan}`][1] : n);
  const shanC = center(yun(sitPalace));
  const xiangC = center(yun(facePalace));

  // 順逆 AC20、AL20：用運盤原星（不是替星）＋坐山地天人查陰陽；原星是 5 時改用坐宮／向宮本身的數
  const yinyang = (n, palace) => STAR_TABLE[`${n === 5 ? palace : n}${yuan}`][0];
  const shanYang = yinyang(yun(sitPalace), sitPalace) === '陽';
  const xiangYang = yinyang(yun(facePalace), facePalace) === '陽';

  // H8 等：陽順 1+MOD(宮-5+中+9-1, 9)；陰逆 1+MOD(-宮+5+中+9-1, 9)
  const fly = (c, forward, p) => (forward ? 1 + mod(p - TAI_JI + c + 8, 9) : 1 + mod(-p + TAI_JI + c + 8, 9));

  const palaces = {};
  for (const p of [TAI_JI, ...GRID_POSITIONS.map(palaceAt)]) {
    palaces[PALACE_NAMES[p]] = { yun: yun(p), shan: fly(shanC, shanYang, p), xiang: fly(xiangC, xiangYang, p) };
  }

  return {
    period,
    sit,
    face,
    kind,
    label: `${NUMERALS[period]}運[${sit}山${face}向]${kind}`, // A1
    palaces,
  };
}
